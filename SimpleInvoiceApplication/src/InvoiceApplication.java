    private void Auto_Total_Calculate() {
        DefaultTableModel dtm = (DefaultTableModel) jT_Product.getModel();
        double Total = 0;
        for (int i = 0; i < jT_Product.getRowCount(); i++) {
            String Unit_Total = dtm.getValueAt(i, 4).toString();
            double Item_Total = Double.parseDouble(Unit_Total);
            Total += Item_Total;
            lbl_Total_Price.setText(Total + "0");
        }
    }

