static class FileTransferable implements java.awt.datatransfer.Transferable {
        private java.util.List<java.io.File> list;
        public FileTransferable(java.util.List<java.io.File> list) { this.list = list; }
        public java.awt.datatransfer.DataFlavor[] getTransferDataFlavors() {
            return new java.awt.datatransfer.DataFlavor[]{java.awt.datatransfer.DataFlavor.javaFileListFlavor};
        }
        public boolean isDataFlavorSupported(java.awt.datatransfer.DataFlavor flavor) {
            return java.awt.datatransfer.DataFlavor.javaFileListFlavor.equals(flavor);
        }
        public Object getTransferData(java.awt.datatransfer.DataFlavor flavor) { return list; }
    }

